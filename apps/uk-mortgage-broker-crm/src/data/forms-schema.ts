export const FORM_SECTIONS: FormSection[] = formSections;

export function allQuestions(): FormQuestion[] {
  const out: FormQuestion[] = [];
  for (const section of FORM_SECTIONS) {
    for (const q of section.questions) {
      out.push(q);
      if (q.repeaterItemSchema) out.push(...q.repeaterItemSchema);
    }
  }
  return out;
}

export function mappingRegister() {
  return allQuestions().map((q) => ({
    formsKey: q.key,
    wording: q.wording,
    crmField: q.crmField,
    dataType: q.dataType,
    importBehaviour: q.importBehaviour,
    protectedField: Boolean(q.protectedField),
    type: q.type,
    required: q.required,
  }));
}

